def update_incident(ticket_number, status):
    allowed_transitions = {
        "Open": {"In Progress"},
        "In Progress": {"Resolved"},
        "Resolved": {"Closed", "In Progress"},
        "Closed": set()
    }

    now = datetime.now(timezone.utc).isoformat()

    with get_connection() as connection:
        with connection.cursor() as cursor:

            cursor.execute("""
                SELECT id, status
                FROM incidents
                WHERE UPPER(ticket_number) = %s
                FOR UPDATE
            """, (ticket_number.upper(),))

            incident = cursor.fetchone()

            if incident is None:
                return None

            incident_id = incident["id"]
            old_status = incident["status"]

            if old_status == status:
                cursor.execute("""
                    SELECT *
                    FROM incidents
                    WHERE id = %s
                """, (incident_id,))
                return cursor.fetchone()

            if status not in allowed_transitions.get(old_status, set()):
                raise ValueError(
                    f"Invalid status transition: {old_status} -> {status}"
                )

            cursor.execute("""
                UPDATE incidents
                SET status = %s, updated_at = %s
                WHERE id = %s
            """, (status, now, incident_id))

            cursor.execute("""
                INSERT INTO incident_status_history (
                    incident_id, old_status, new_status, changed_at
                )
                VALUES (%s, %s, %s, %s)
            """, (incident_id, old_status, status, now))

            cursor.execute("""
                SELECT *
                FROM incidents
                WHERE id = %s
            """, (incident_id,))

            return cursor.fetchone()


def save_conversation(ticket_number, user_message, assistant_response):
    now = datetime.now(timezone.utc).isoformat()

    with get_connection() as connection:
        with connection.cursor() as cursor:

            cursor.execute("""
                SELECT id
                FROM incidents
                WHERE UPPER(ticket_number) = %s
            """, (ticket_number.upper(),))

            incident = cursor.fetchone()

            if incident is None:
                return None

            cursor.execute("""
                INSERT INTO conversation_history (
                    incident_id, user_message,
                    assistant_response, created_at
                )
                VALUES (%s, %s, %s, %s)
            """, (
                incident["id"],
                user_message,
                assistant_response,
                now
            ))

            return True


def get_conversation_history(ticket_number):
    with get_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute("""
                SELECT
                    ch.id,
                    ch.incident_id,
                    ch.user_message,
                    ch.assistant_response,
                    ch.created_at
                FROM conversation_history ch
                JOIN incidents i ON i.id = ch.incident_id
                WHERE UPPER(i.ticket_number) = %s
                ORDER BY ch.id ASC
            """, (ticket_number.upper(),))

            return cursor.fetchall()


def get_status_history(ticket_number):
    with get_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute("""
                SELECT
                    h.id,
                    h.incident_id,
                    h.old_status,
                    h.new_status,
                    h.changed_at
                FROM incident_status_history h
                JOIN incidents i ON i.id = h.incident_id
                WHERE UPPER(i.ticket_number) = %s
                ORDER BY h.id ASC
            """, (ticket_number.upper(),))

            return cursor.fetchall()