import os
from datetime import datetime, timezone

import psycopg
from psycopg.rows import dict_row
from dotenv import load_dotenv

load_dotenv()

DATABASE_URL = os.getenv("DATABASE_URL")

if not DATABASE_URL:
    raise RuntimeError("DATABASE_URL not found. Check your .env file.")


def get_connection():
    return psycopg.connect(
        DATABASE_URL,
        sslmode="require",
        connect_timeout=15,
        row_factory=dict_row
    )


def initialize_database():
    with get_connection() as connection:
        with connection.cursor() as cursor:

            cursor.execute("""
                CREATE TABLE IF NOT EXISTS incidents (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    ticket_number TEXT UNIQUE,
                    title TEXT NOT NULL,
                    description TEXT NOT NULL,
                    category TEXT NOT NULL,
                    priority TEXT NOT NULL DEFAULT 'Medium',
                    status TEXT NOT NULL DEFAULT 'Open',
                    created_at TEXT NOT NULL,
                    updated_at TEXT NOT NULL
                )
            """)

            cursor.execute("""
                CREATE TABLE IF NOT EXISTS conversation_history (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    incident_id BIGINT NOT NULL REFERENCES incidents(id)
                        ON DELETE CASCADE,
                    user_message TEXT NOT NULL,
                    assistant_response TEXT NOT NULL,
                    created_at TEXT NOT NULL
                )
            """)

            cursor.execute("""
                CREATE TABLE IF NOT EXISTS incident_status_history (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    incident_id BIGINT NOT NULL REFERENCES incidents(id)
                        ON DELETE CASCADE,
                    old_status TEXT,
                    new_status TEXT NOT NULL,
                    changed_at TEXT NOT NULL
                )
            """)

            cursor.execute("""
                CREATE INDEX IF NOT EXISTS idx_incidents_status_id
                ON incidents(status, id DESC)
            """)


def create_incident(title, description, category, priority="Medium"):
    now = datetime.now(timezone.utc).isoformat()

    with get_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute("""
                INSERT INTO incidents (
                    title, description, category, priority,
                    status, created_at, updated_at
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s)
                RETURNING id
            """, (
                title, description, category, priority,
                "Open", now, now
            ))

            incident_id = cursor.fetchone()["id"]
            ticket_number = f"INC{incident_id:06d}"

            cursor.execute("""
                UPDATE incidents
                SET ticket_number = %s
                WHERE id = %s
                RETURNING *
            """, (ticket_number, incident_id))

            return cursor.fetchone()


def list_incidents(
    limit=None,
    offset=0,
    search="",
    status="All",
    priority="All",
    category="All"
):
    query = "SELECT * FROM incidents WHERE 1=1"
    params = []

    if search:
        query += """
            AND (
                LOWER(ticket_number) LIKE %s
                OR LOWER(title) LIKE %s
            )
        """
        search_value = f"%{search.lower()}%"
        params.extend([search_value, search_value])

    if status != "All":
        query += " AND status = %s"
        params.append(status)

    if priority != "All":
        query += " AND priority = %s"
        params.append(priority)

    if category != "All":
        query += " AND category = %s"
        params.append(category)

    query += " ORDER BY id DESC"

    if limit is not None:
        query += " LIMIT %s OFFSET %s"
        params.extend([limit, offset])

    with get_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute(query, params)
            return cursor.fetchall()


